const dictionaries: Record<Lang, Record<Key, string>> = { en, fil, es }

export const isLang = (v: string): v is Lang => v in dictionaries

export type TFn = (key: Key, vars?: Vars) => string
export type TnFn = (base: PluralBase, n: number) => string

export function translate(lang: string, key: Key, vars?: Vars): string {
  const dict = isLang(lang) ? dictionaries[lang] : en
  const text = dict[key] ?? en[key]
  return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : text
}

/** Picks the singular or plural form, e.g. tn('dash.notes', 3) → "3 notes". */
export function translatePlural(lang: string, base: PluralBase, n: number): string {
  return translate(lang, `${base}_${n === 1 ? 'one' : 'other'}` as Key, { n })
}
